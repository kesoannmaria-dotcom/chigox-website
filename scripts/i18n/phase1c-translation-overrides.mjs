const businessScopePattern = /(?:support scope|quotation scope|scope of each offer|scope for your requirement|warranty scope|total quotation scope|supply scope)/i;

function normalizeInstrumentScope(source, translation, languageKey) {
  if (!/\bscopes?\b/i.test(source) || businessScopePattern.test(source)) return translation;
  if (languageKey === "es") {
    return translation
      .replace(/\balcances\b/gi, "endoscopios")
      .replace(/\b(?:alcance|ámbito|visor|osciloscopio)\b/gi, "endoscopio");
  }
  if (languageKey === "tr") {
    return translation
      .replace(/\bkapsamdan\b/giu, "endoskoptan")
      .replace(/\bkapsamlar\b/giu, "endoskoplar")
      .replace(/\bkapsama\b/giu, "endoskopa")
      .replace(/\bkapsamı\b/giu, "endoskopu")
      .replace(/\bkapsamın\b/giu, "endoskopun")
      .replace(/\bkapsamdır\b/giu, "endoskoptur")
      .replace(/\b(?:kapsam|dürbün|osiloskop|skop)\b/giu, "endoskop")
      .replace(/\bendoskopı\b/giu, "endoskopu")
      .replace(/değiştirme endoskopuna/giu, "yedek endoskopa")
      .replace(/çok kapsamlı bir endoskopi planı/giu, "çoklu endoskoplu bir endoskopi planı")
      .replace(/tek kapsamlı bir karardan/giu, "tek bir endoskop kararından")
      .replace(/en uzun kapsamdır/giu, "en uzun endoskoptur");
  }
  if (languageKey === "de") {
    return translation
      .replace(/\bZielfernrohrtyp\b/g, "Endoskoptyp")
      .replace(/\bZielfernrohrs\b/g, "Endoskops")
      .replace(/\bZielfernrohre\b/g, "Endoskope")
      .replace(/\b(?:Zielfernrohr|Oszilloskop|Umfang|Bereich)\b/g, "Endoskop")
      .replace(/\bBereiche\b/g, "Endoskope");
  }
  if (languageKey === "it") {
    return translation
      .replace(/\bambiti\b/gi, "endoscopi")
      .replace(/\b(?:ambito|portata|mirino|oscilloscopio)\b/gi, "endoscopio");
  }
  if (languageKey === "pl") {
    return translation
      .replace(/\bzakresie\b/gi, "endoskopie")
      .replace(/\bzakresu\b/gi, "endoskopu")
      .replace(/\bzakres\b/gi, "endoskop")
      .replace(/\b(?:luneta|oscyloskop)\b/gi, "endoskop");
  }
  return translation.replace(/범위|스코프/g, "내시경");
}

function normalizeMedicalTerminology(translation, languageKey) {
  if (languageKey === "es") {
    return translation
      .replace(/matriz en fases/gi, "matriz faseada")
      .replace(/matriz en fase/gi, "matriz faseada")
      .replace(/arreglo en fase/gi, "matriz faseada")
      .replace(/o en fase/gi, "o de matriz faseada")
      .replace(/y en fase/gi, "y de matriz faseada");
  }
  if (languageKey === "tr") {
    return translation
      .replace(/Dışbükey/g, "Konveks")
      .replace(/dışbükey/g, "konveks")
      .replace(/Doğrusal/g, "Lineer")
      .replace(/doğrusal/g, "lineer")
      .replace(/Aşamalı Dizi/g, "Faz Dizilimli")
      .replace(/aşamalı dizi/g, "faz dizilimli")
      .replace(/fazlı dizilimli/gi, "faz dizilimli")
      .replace(/faz dizili\b/gi, "faz dizilimli")
      .replace(/faz dizilimlimli/gi, "faz dizilimli")
      .replace(/Taşınabilir El Veteriner Röntgen Sistemi/g, "Taşınabilir El Tipi Veteriner Röntgen Sistemi");
  }
  if (languageKey === "de") {
    return translation
      .replace(/Tragbares tragbares/g, "Tragbares handgeführtes")
      .replace(/tragbares tragbares/g, "tragbares handgeführtes")
      .replace(/10\.3-inch Touchscreen/g, "10.3-Zoll-Touchscreen")
      .replace(/CGU-LCP 3-in-1 Scanner/g, "CGU-LCP 3-in-1-Ultraschallscanner");
  }
  if (languageKey === "it") {
    return translation
      .replace(/array a fase/gi, "phased array")
      .replace(/lineare vs convesso/gi, "lineare vs convessa")
      .replace(/portatile tascabile/gi, "portatile palmare")
      .replace(/^Email CHIGOX$/i, "Invia un'e-mail a CHIGOX")
      .replace(/^Email:$/i, "E-mail:");
  }
  if (languageKey === "pl") {
    return translation
      .replace(/przenośnego ultradźwięku/gi, "przenośnego ultrasonografu")
      .replace(/przenośny ultradźwięk/gi, "przenośny ultrasonograf")
      .replace(/przenośnych ultradźwięków/gi, "przenośnych ultrasonografów")
      .replace(/ultradźwięk weterynaryjny/gi, "ultrasonograf weterynaryjny")
      .replace(/skanera ultradźwiękowego/gi, "ultrasonografu")
      .replace(/skaner ultradźwiękowy/gi, "ultrasonograf")
      .replace(/system ultradźwiękowy/gi, "system ultrasonograficzny")
      .replace(/konkawow/gi, "konweksow")
      .replace(/sondę convex/gi, "głowicę konweksową")
      .replace(/ultrasonografu wypukłego/gi, "ultrasonografu konweksowego")
      .replace(/sond ultradźwiękowych: liniowa vs wypukła vs matrycowa/gi, "głowic ultrasonograficznych: liniowa vs konweksowa vs fazowana")
      .replace(/^przenośny ultrasonograf/gi, "Przenośny ultrasonograf")
      .replace(/^Email CHIGOX$/i, "Napisz e-mail do CHIGOX")
      .replace(/^Email:$/i, "E-mail:");
  }
  return translation
    .replace(/볼록\(transvaginal\)/g, "컨벡스 및 질식")
    .replace(/볼록/g, "컨벡스")
    .replace(/수의사 마취기/g, "수의용 마취기")
    .replace(/수의학 마취기/g, "수의용 마취기")
    .replace(/클리닉용 수의용/g, "클리닉용 수의");
}

export function applyPhase1CTranslationReview(catalog, languageKey) {
  const reviewed = {};
  for (const [source, translation] of Object.entries(catalog)) {
    reviewed[source] = normalizeMedicalTerminology(normalizeInstrumentScope(source, translation, languageKey), languageKey);
  }
  return { ...reviewed, ...phase1CTranslationOverrides[languageKey] };
}
